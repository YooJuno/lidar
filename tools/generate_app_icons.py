#!/usr/bin/env python3
"""Generate native app icons from the repository's canonical SVG.
Needs Pillow and CairoSVG (uv run --with pillow --with cairosvg this_script).
Generated files are committed; normal builds need no Python image packages.
"""
import io
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
FOLDER=ROOT/'resources/icons'

def render(size):
    import cairosvg
    png=cairosvg.svg2png(url=str(FOLDER/'lidar-studio.svg'),output_width=size,output_height=size)
    return Image.open(io.BytesIO(png)).convert('RGBA')


def rle(image):
    pixels=list(image.get_flattened_data() if hasattr(image,"get_flattened_data") else image.getdata());output=[];i=0
    while i<len(pixels):
        count=1
        while i+count<len(pixels) and pixels[i+count]==pixels[i] and count<255:count+=1
        output.extend((count,*pixels[i]));i+=count
    return output

def main():
    images={size:render(size) for size in (16,24,32,48,64,128,256,512,1024)}
    for size,image in images.items():image.save(FOLDER/f'lidar-studio-{size}.png')
    images[1024].save(FOLDER/'lidar-studio.ico',sizes=[(s,s) for s in (16,24,32,48,64,128,256)])
    images[1024].save(FOLDER/'lidar-studio.icns')
    header='''// Generated by tools/generate_app_icons.py from resources/icons/lidar-studio.svg.
// Run-length encoded RGBA for GLFW; native packages use ICO / ICNS / hicolor.
#pragma once
#include <array>
#include <cstddef>
namespace lidar_viewer::app_icon {
'''
    for size in (32,128):
        data=rle(images[size]);header+=f'inline constexpr unsigned char rgba{size}[]={{\n'
        header+='\n'.join('  '+','.join(str(v) for v in data[i:i+25])+',' for i in range(0,len(data),25))+'\n};\n'
    header+='''template<std::size_t Pixels,std::size_t N>
std::array<unsigned char,Pixels*4> Decode(const unsigned char (&data)[N])
{
  std::array<unsigned char,Pixels*4> result{};std::size_t out=0;
  for (std::size_t i=0;i+4<N;i+=5)
    for (unsigned int count=0;count<data[i] && out+4<=result.size();++count)
      for (std::size_t channel=1;channel<=4;++channel) result[out++]=data[i+channel];
  return result;
}
} // namespace lidar_viewer::app_icon
'''
    (ROOT/'include/lidar_viewer/app_icon.hpp').write_text(header)
    print('Generated SVG-derived PNG, ICO, ICNS and GLFW RGBA icons.')

if __name__=='__main__':main()
